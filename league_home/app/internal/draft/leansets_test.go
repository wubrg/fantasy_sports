// TestDuplicateSetIsLoadedOnce — "mine,mine" must not make a set argue with
// itself.
func TestDuplicateSetIsLoadedOnce(t *testing.T) {
	cfg := leanDir(t, map[string]string{"mine": mineCSV})
	merged, sets, err := LoadLeanSets(cfg, []string{"mine", "mine"})
	if err != nil {
		t.Fatal(err)
	}
	if len(sets) != 1 {
		t.Errorf("loaded the same set %d times", len(sets))
	}
	if walker := merged[normalizeName("Kenneth Walker")]; len(walker.Others) != 0 {
		t.Errorf("a set disagreed with itself: %+v", walker.Others)
	}
}
